-- Video categories widened (lyrical, promo, interview, event, bts). movie_videos
-- was created outside this file; drop its old CHECK so new categories insert.
alter table if exists public.movie_videos drop constraint if exists movie_videos_category_check;

-- Community: user ratings & reviews, polls, quiz, admin-entered box office.
create table if not exists public.movie_user_ratings (
  user_id bigint not null references public.users(id) on delete cascade,
  movie_id bigint not null,
  rating integer check (rating is null or (rating >= 1 and rating <= 5)),
  watch_status text check (watch_status is null or watch_status in ('watched', 'want', 'no')),
  updated_at text not null,
  primary key (user_id, movie_id)
);

create index if not exists idx_movie_user_ratings_movie_id on public.movie_user_ratings(movie_id);

create table if not exists public.movie_user_reviews (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  movie_id bigint not null,
  movie_title text not null,
  author_name text not null,
  title text not null,
  body text not null,
  rating integer check (rating is null or (rating >= 1 and rating <= 5)),
  status text not null check (status in ('published', 'hidden')),
  created_at text not null,
  updated_at text not null,
  unique (user_id, movie_id)
);

create index if not exists idx_movie_user_reviews_movie_id on public.movie_user_reviews(movie_id);

create table if not exists public.polls (
  id bigint generated by default as identity primary key,
  question text not null,
  options text not null,
  movie_id bigint,
  movie_title text,
  is_active integer not null default 1 check (is_active in (0, 1)),
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at text not null
);

create table if not exists public.poll_votes (
  poll_id bigint not null references public.polls(id) on delete cascade,
  voter_key text not null,
  option_index integer not null,
  created_at text not null,
  primary key (poll_id, voter_key)
);

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  question text not null,
  options text not null,
  correct_index integer not null,
  category text not null default 'General',
  is_active integer not null default 1 check (is_active in (0, 1)),
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at text not null
);

create table if not exists public.quiz_answers (
  question_id bigint not null references public.quiz_questions(id) on delete cascade,
  voter_key text not null,
  option_index integer not null,
  is_correct integer not null default 0 check (is_correct in (0, 1)),
  created_at text not null,
  primary key (question_id, voter_key)
);

create table if not exists public.movie_box_office (
  movie_id bigint primary key,
  movie_title text not null,
  poster_path text,
  release_date text,
  worldwide_gross text not null,
  note text,
  as_of text,
  added_by_user_id bigint references public.users(id) on delete set null,
  updated_at text not null
);

