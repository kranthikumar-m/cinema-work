create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text,
  email text not null unique,
  password_hash text not null,
  role text not null check (role in ('admin', 'editor', 'viewer')),
  image text,
  is_active integer not null default 1 check (is_active in (0, 1)),
  last_login_at text,
  created_at text not null,
  updated_at text not null
);

create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash text not null unique,
  expires_at text not null,
  created_at text not null
);

create table if not exists public.movie_backdrop_overrides (
  movie_id bigint primary key,
  selected_backdrop_path text not null,
  source text not null default 'tmdb',
  selected_by_user_id bigint references public.users(id) on delete set null,
  created_at text not null,
  updated_at text not null
);

create table if not exists public.password_reset_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash text not null unique,
  expires_at text not null,
  used_at text,
  created_at text not null
);

create table if not exists public.movie_trending_signals (
  movie_id bigint primary key,
  mention_count integer not null default 0,
  mentions_updated_at text,
  admin_order integer,
  admin_pinned integer not null default 0 check (admin_pinned in (0, 1)),
  updated_at text not null
);

create table if not exists public.validated_year_movies (
  year integer not null,
  movie_id bigint not null,
  payload text not null,
  created_at text not null,
  primary key (year, movie_id)
);

create table if not exists public.validated_year_freezes (
  year integer primary key,
  frozen_at text not null,
  movie_count integer not null
);

create table if not exists public.validated_year_progress (
  year integer not null,
  quarter integer not null,
  movie_count integer not null,
  completed_at text not null,
  primary key (year, quarter)
);

create table if not exists public.movie_hidden_videos (
  id bigint generated by default as identity primary key,
  movie_id bigint not null,
  youtube_key text not null,
  created_at text not null,
  unique (movie_id, youtube_key)
);

create index if not exists idx_movie_hidden_videos_movie_id on public.movie_hidden_videos(movie_id);

create table if not exists public.hidden_movies (
  movie_id bigint primary key,
  added_by_user_id bigint references public.users(id) on delete set null,
  created_at text not null
);

create table if not exists public.movie_release_overrides (
  movie_id bigint primary key,
  release_date text,
  aliases text,
  added_by_user_id bigint references public.users(id) on delete set null,
  updated_at text not null
);

create table if not exists public.movie_detail_overrides (
  movie_id bigint primary key,
  facts text,
  companies text,
  added_by_user_id bigint references public.users(id) on delete set null,
  updated_at text not null
);

create index if not exists idx_sessions_token_hash on public.sessions(token_hash);
create index if not exists idx_sessions_user_id on public.sessions(user_id);
create index if not exists idx_users_role on public.users(role);
create index if not exists idx_users_email on public.users(email);
create index if not exists idx_password_reset_tokens_hash on public.password_reset_tokens(token_hash);
create index if not exists idx_password_reset_tokens_user_id on public.password_reset_tokens(user_id);
